/*
  Phase 1 data integrity:
  - Normalizes order lines into order_items.
  - Backfills existing JSON order lines before enforcing constraints.
  - Keeps orders.items temporarily for compatibility with the pre-Phase 2 checkout.
*/

CREATE TABLE IF NOT EXISTS public.order_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id integer NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  product_name text NOT NULL,
  unit_price numeric(10, 2) NOT NULL,
  quantity integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT order_items_unit_price_nonnegative CHECK (unit_price >= 0),
  CONSTRAINT order_items_quantity_positive CHECK (quantity > 0),
  CONSTRAINT order_items_order_product_unique UNIQUE (order_id, product_id)
);

INSERT INTO public.order_items (order_id, product_id, product_name, unit_price, quantity)
SELECT
  o.id,
  (item->>'productId')::integer,
  item->>'name',
  (item->>'price')::numeric(10, 2),
  (item->>'quantity')::integer
FROM public.orders AS o
CROSS JOIN LATERAL jsonb_array_elements(o.items) AS item
WHERE jsonb_typeof(o.items) = 'array'
  AND item ? 'productId'
  AND item ? 'name'
  AND item ? 'price'
  AND item ? 'quantity'
ON CONFLICT (order_id, product_id) DO NOTHING;

ALTER TABLE public.products
  ADD CONSTRAINT products_price_nonnegative CHECK (price >= 0),
  ADD CONSTRAINT products_stock_nonnegative CHECK (stock >= 0),
  ADD CONSTRAINT products_rating_range CHECK (rating >= 0 AND rating <= 5);

ALTER TABLE public.orders
  ADD CONSTRAINT orders_total_nonnegative CHECK (total >= 0),
  ADD CONSTRAINT orders_customer_name_nonempty CHECK (length(trim(customer_name)) > 0),
  ADD CONSTRAINT orders_email_nonempty CHECK (length(trim(email)) > 3),
  ADD CONSTRAINT orders_items_array CHECK (jsonb_typeof(items) = 'array');

CREATE INDEX IF NOT EXISTS idx_order_items_order_id ON public.order_items(order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_product_id ON public.order_items(product_id);